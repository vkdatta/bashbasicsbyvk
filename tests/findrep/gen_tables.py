#!/usr/bin/env python3
"""Generates script/file/engine/bvk-fr/src/bashbasicsbyvk_fr_tables.c from Python's Unicode data.

Run:  python3 -I tests/findrep/gen_tables.py > script/file/engine/bvk-fr/src/bashbasicsbyvk_fr_tables.c

The engine (bvk-fr) has no libc locale / ICU dependency, so case mapping and the \\w \\d \\s classes come from these
static tables: identical on every target (glibc static, musl, Android bionic) and identical to Python's `re` for str patterns.
"""
import sys, unicodedata

MAXCP = 0x10FFFF


def ranges(pred):
    out, lo = [], None
    for cp in range(MAXCP + 1):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and lo is None:
            lo = cp
        elif not ok and lo is not None:
            out.append((lo, cp - 1)); lo = None
    if lo is not None:
        out.append((lo, MAXCP))
    return out


def pairs(fn):
    out = []
    for cp in range(MAXCP + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if len(m) == 1 and m != c:
            out.append((cp, ord(m)))
    return out


def emit_pairs(name, rows):
    print("const uint32_t %s[][2] = {" % name)
    for i in range(0, len(rows), 6):
        print("    " + " ".join("{%d,%d}," % r for r in rows[i:i + 6]))
    print("};")
    print("const size_t %s_n = %d;" % (name, len(rows)))


print("/* GENERATED by tests/findrep/gen_tables.py (Python %s, Unicode %s). Do not edit by hand. */" %
      (sys.version.split()[0], unicodedata.unidata_version))
print('#include "bashbasicsbyvk_fr.h"')
print()
emit_pairs("fr_lower_tab", pairs(str.lower))
print()
emit_pairs("fr_upper_tab", pairs(str.upper))
print()
emit_pairs("fr_word_rng", ranges(lambda c: c.isalnum() or c == "_"))
print()
emit_pairs("fr_digit_rng", ranges(lambda c: c.isdecimal()))
print()
emit_pairs("fr_space_rng", ranges(lambda c: c.isspace()))
